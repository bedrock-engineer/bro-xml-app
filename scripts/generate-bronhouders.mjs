/**
 * Regenerates app/util/bronhouders-data.ts from the public list of
 * organizations registered with the BRO:
 * https://basisregistratieondergrond.nl/service-contact/formulieren/aangemeld-bro/
 *
 * The page lists every registered organization as "Name | KvK-number",
 * with "(B)" marking bronhouders. BRO XML only carries the KvK number
 * (deliveryAccountableParty), so this mapping is needed to display names.
 *
 * Usage: node scripts/generate-bronhouders.mjs
 */
import { writeFile } from "node:fs/promises";

const SOURCE_URL =
  "https://basisregistratieondergrond.nl/service-contact/formulieren/aangemeld-bro/";
const OUTPUT = new URL("../app/util/bronhouders-data.ts", import.meta.url);

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Fetch failed: ${response.status} ${response.statusText}`);
}
const html = await response.text();

// The page uses zero-width spaces and non-breaking spaces inside the
// "(B)" bronhouder marker; strip them before matching.
const cleaned = html.replaceAll("​", "").replaceAll(" ", " ");

const decode = (text) =>
  text
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&#39;", "'")
    .replaceAll("&quot;", '"');

const entries = new Map();
for (const line of cleaned.split(
  /<br\s*\/?>|<\/p>|<p[^>]*>|<\/li>|<li[^>]*>/,
)) {
  const text = decode(line.replaceAll(/<[^>]+>/g, " ")).trim();
  const match = /^(.*?)\s*\|\s*(\d{8})(\s*\(B\))?\s*$/.exec(text);
  if (!match) continue;
  const name = match[1].replaceAll(/\s+/g, " ").trim();
  if (!name || name.includes("Organisatienaam")) continue;
  entries.set(match[2], name);
}

if (entries.size < 500) {
  throw new Error(
    `Only ${entries.size} organizations parsed; page structure likely changed`,
  );
}

const sorted = [...entries.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = sorted
  .map(([kvk, name]) => `  "${kvk}": "${name.replaceAll('"', '\\"')}",`)
  .join("\n");

const date = new Date().toISOString().slice(0, 10);
await writeFile(
  OUTPUT,
  `// Generated by scripts/generate-bronhouders.mjs on ${date}. Do not edit.
// Source: ${SOURCE_URL}
export const bronhouderNames: Record<string, string> = {
${body}
};
`,
);

console.log(`Wrote ${entries.size} organizations to ${OUTPUT.pathname}`);
